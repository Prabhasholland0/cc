import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { DEFAULT_PRICING } from '../src/data/defaultPricing';
import { calculateQuote, defaultSelection, indiaDate, startingRate } from '../src/lib/pricing';
import { submitEnquiryApi } from '../src/services/api';
const config = structuredClone(DEFAULT_PRICING);
const selection = defaultSelection(config, 'full-home', '2bhk');
assert.equal(calculateQuote(config, selection).total, 3499);
config.services.find(s => s.id === 'full-home')!.packages.find(p => p.id === '2bhk')!.price = 4100;
assert.equal(calculateQuote(config, selection).total, 4100);
assert.equal(calculateQuote(config, { ...selection, extraBathrooms: 2, priority: true }).total, 5598);
config.emergencyFee = 0;
assert.equal(calculateQuote(config, { ...selection, priority: true }).total, 4100);
assert.equal(calculateQuote(config, defaultSelection(config, 'express-addons', 'addon-fan')).total, 499);
assert.equal(calculateQuote(config, defaultSelection(config, 'sofa-carpet', 'sofa-seat')).total, 749);
assert.throws(() => calculateQuote(config, { ...selection, quantities: {} }));
assert.throws(() => calculateQuote(config, { ...selection, quantities: { '2bhk': -1 } }));
assert.throws(() => calculateQuote(config, { ...selection, quantities: { missing: 1 } }));
assert.throws(() => calculateQuote(config, { ...selection, quantities: { '2bhk': 1.5 } }));
assert.equal(startingRate(config.services[0]), 2499);
const directory = await mkdtemp(path.join(tmpdir(), 'clean-corners-test-'));
const port = 33000 + Math.floor(Math.random() * 10000);
const token = randomUUID();
const server = spawn(process.execPath, ['node_modules/tsx/dist/cli.mjs', 'server/index.ts'], { cwd: process.cwd(), env: { ...process.env, PORT: String(port), DATA_DIR: directory, ADMIN_SECRET: token }, windowsHide: true, stdio: 'pipe' });
let output = '';
server.stdout.on('data', data => { output += data; }); server.stderr.on('data', data => { output += data; });
const base = `http://127.0.0.1:${port}`;
const api = async (url: string, method = 'GET', body?: unknown, auth = false) => fetch(base + url, { method, headers: { 'Content-Type': 'application/json', ...(auth ? { 'x-admin-token': token } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
try {
  let ready = false;
  for (let attempt = 0; attempt < 50; attempt++) { try { if ((await api('/api/health')).ok) { ready = true; break; } } catch {} await new Promise(resolve => setTimeout(resolve, 150)); }
  assert.ok(ready, output);
  assert.equal((await api('/api/enquiries')).status, 401);
  assert.equal((await api('/api/audit')).status, 401);
  assert.equal((await api('/api/pricing', 'PUT', config, true)).status, 200);
  const live = await (await api('/api/pricing')).json();
  const quote = calculateQuote(live, selection);
  const payload = { requestId: randomUUID(), selection, customerName: 'Website QA', phone: '9000000000', area: 'Test locality', address: 'Test address for isolated QA', preferredDate: indiaDate(1), preferredTimeSlot: 'Morning: 9am–12pm', estimatedPrice: quote.total, notes: 'Test only; do not contact' };
  assert.equal((await api('/api/enquiries', 'POST', { ...payload, phone: '123' })).status, 400);
  assert.equal((await api('/api/enquiries', 'POST', { ...payload, preferredDate: '2020-01-01' })).status, 400);
  assert.equal((await api('/api/enquiries', 'POST', { ...payload, estimatedPrice: 1 })).status, 409);
  const response = await api('/api/enquiries', 'POST', payload);
  assert.equal(response.status, 201, await response.clone().text());
  const created = await response.json();
  assert.match(created.enquiryId, /^CC-/);
  assert.match(created.notice, /not a confirmed appointment/);
  const replay = await api('/api/enquiries', 'POST', payload);
  assert.equal(replay.status, 200);
  assert.equal((await replay.json()).enquiryId, created.enquiryId);
  assert.equal((await api('/api/enquiries', 'POST', { ...payload, address: 'Changed after ambiguous save' })).status, 409);
  const route = `/api/enquiries/${created.enquiryId}`;
  assert.equal((await api(route, 'PATCH', { status: 'invalid' }, true)).status, 400);
  assert.equal((await api(route, 'PATCH', { status: 'service_confirmed' }, true)).status, 400);
  assert.equal((await api(route, 'PATCH', { status: 'contacted', adminNotes: 'Called customer', followUpDate: indiaDate(1) }, true)).status, 200);
  assert.equal((await api(route, 'PATCH', { status: 'service_confirmed', appointmentDate: indiaDate(1), appointmentTime: '10am', assignedTeam: 'QA team' }, true)).status, 200);
  assert.equal((await api(route, 'PATCH', { status: 'completed' }, true)).status, 200);
  const records = await (await api('/api/enquiries', 'GET', undefined, true)).json();
  assert.equal(records.length, 1);
  assert.equal(records[0].adminNotes, 'Called customer');
  assert.equal(records[0].status, 'completed');
  assert.equal(records[0].estimatedPrice, quote.total);
  assert.equal(JSON.parse(await readFile(path.join(directory, 'enquiries.json'), 'utf8'))[0].appointmentTime, '10am');
  const badConfig = structuredClone(config); badConfig.services[0].packages[0].price = -10;
  assert.equal((await api('/api/pricing', 'PUT', badConfig, true)).status, 400);
  assert.equal((await api('/api/enquiries/export', 'GET', undefined, true)).status, 200);
  assert.equal((await api('/services/full-home')).status, 200);
  const areaPage = await api('/areas/neredmet-rk-puram');
  assert.equal(areaPage.status, 200);
  if (existsSync('dist/areas/neredmet-rk-puram/index.html')) assert.match(await areaPage.text(), /Home Cleaning in Neredmet &amp; RK Puram/);
  const callback = { requestId: randomUUID(), name: 'Website QA', phone: '9000000001', preferredTime: 'As soon as possible', serviceId: 'kitchen', website: '' };
  assert.equal((await api('/api/callbacks', 'POST', { ...callback, phone: '12345' })).status, 400);
  assert.equal((await api('/api/callbacks', 'POST', { ...callback, website: 'spam.example' })).status, 400);
  const callbackResponse = await api('/api/callbacks', 'POST', callback);
  assert.equal(callbackResponse.status, 201);
  const callbackId = (await callbackResponse.json()).callbackId;
  assert.match(callbackId, /^CB-/);
  assert.equal((await (await api('/api/callbacks', 'POST', callback)).json()).callbackId, callbackId);
  assert.equal((await api('/api/callbacks')).status, 401);
  assert.equal((await api(`/api/callbacks/${callbackId}`, 'PATCH', { status: 'called' }, true)).status, 200);
  const callbacks = await (await api('/api/callbacks', 'GET', undefined, true)).json();
  assert.equal(callbacks.length, 1);
  assert.equal(callbacks[0].status, 'called');
  // Spam limit: 5 new callback requests per network per hour.
  for (let i = 0; i < 4; i++) assert.equal((await api('/api/callbacks', 'POST', { ...callback, requestId: randomUUID() })).status, 201);
  assert.equal((await api('/api/callbacks', 'POST', { ...callback, requestId: randomUUID() })).status, 429);
  // Customer tracking: reference + mobile number, reschedule and cancel requests.
  assert.equal((await api('/api/track', 'POST', { reference: created.enquiryId, phone: payload.phone })).status, 200);
  assert.equal((await api('/api/track/change', 'POST', { reference: created.enquiryId, phone: payload.phone, type: 'cancel' })).status, 409, 'completed bookings cannot be cancelled');
  const second = { ...payload, requestId: randomUUID(), preferredDate: indiaDate(2) };
  const secondId = (await (await api('/api/enquiries', 'POST', second)).json()).enquiryId;
  assert.equal((await api('/api/track', 'POST', { reference: secondId, phone: '9999999999' })).status, 404);
  assert.equal((await api('/api/track', 'POST', { reference: 'nonsense', phone: second.phone })).status, 400);
  const tracked = await (await api('/api/track', 'POST', { reference: secondId.toLowerCase(), phone: second.phone })).json();
  assert.equal(tracked.booking.status, 'new');
  assert.equal(tracked.booking.canChangeOnline, true);
  assert.equal(tracked.booking.address, undefined, 'tracking must not expose the address');
  assert.equal((await api('/api/track/change', 'POST', { reference: secondId, phone: second.phone, type: 'reschedule' })).status, 400);
  const rescheduled = await api('/api/track/change', 'POST', { reference: secondId, phone: second.phone, type: 'reschedule', preferredDate: indiaDate(3), preferredTimeSlot: 'Afternoon: 1pm–4pm', reason: 'Guests visiting' });
  assert.equal(rescheduled.status, 200);
  assert.equal((await rescheduled.json()).booking.customerRequest.type, 'reschedule');
  assert.equal((await api(`/api/enquiries/${secondId}`, 'PATCH', { customerRequestHandled: true }, true)).status, 200);
  const cancelledBooking = await (await api('/api/track/change', 'POST', { reference: secondId, phone: second.phone, type: 'cancel' })).json();
  assert.equal(cancelledBooking.booking.status, 'cancelled');
  assert.equal((await api('/api/track/change', 'POST', { reference: secondId, phone: second.phone, type: 'cancel' })).status, 409);
  const staffView = (await (await api('/api/enquiries', 'GET', undefined, true)).json()).find((record: { id: string }) => record.id === secondId);
  assert.equal(staffView.customerRequest.type, 'cancel');
  assert.equal(staffView.customerRequest.handled, false);
  const today = { ...payload, requestId: randomUUID(), preferredDate: indiaDate() };
  const todayId = (await (await api('/api/enquiries', 'POST', today)).json()).enquiryId;
  assert.equal((await api('/api/track/change', 'POST', { reference: todayId, phone: today.phone, type: 'cancel' })).status, 409, 'same-day changes need a phone call');
  // Staff lockout: 10 wrong passcodes lock staff login for 15 minutes, even for the right passcode.
  const wrong = () => fetch(base + '/api/enquiries', { headers: { 'x-admin-token': 'wrong' } });
  let wrongStatuses = 0;
  while ((await wrong()).status === 401) wrongStatuses++;
  assert.ok(wrongStatuses <= 10, 'lockout must start by the 11th wrong passcode');
  assert.equal((await api('/api/enquiries', 'GET', undefined, true)).status, 429);
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async () => { throw new Error('Simulated network failure'); };
  try { assert.equal((await submitEnquiryApi({ ...payload, serviceId: 'full-home', serviceName: 'Full Home Cleaning' })).success, false); } finally { globalThis.fetch = originalFetch; }
  console.log('PASS: shared pricing, minimums, zero fee, invalid quantities, API validation, stale-price rejection, persisted enquiry, retry deduplication, staff queue transitions, appointment guard, notes preservation, CSV, service URL, area pages, callback requests, booking tracking with reschedule/cancel rules, spam limits, staff lockout, and honest offline failure.');
} finally {
  server.kill();
  await new Promise(resolve => server.once('exit', resolve));
  if (!directory.startsWith(path.join(tmpdir(), 'clean-corners-test-'))) throw new Error('Unexpected test directory');
  await rm(directory, { recursive: true, force: true });
}
